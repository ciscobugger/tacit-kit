#!/usr/bin/env python3
"""generate.py: Tacit's tokens/tokens.json into what reads it.

  generate.py qml <Tacit.qml>        rewrite the block between the tacit-kit markers in the shell's Tacit.qml
  generate.py css [colors.json]      generated/tokens.css (colours resolved when a palette is given)
  generate.py tables                 generated/tables.md, the value tables the docs pages include
  generate.py kit [colors.json]      qml/Tacit/Kit/Defaults.qml: the module's own tokens (colours resolved for a palette,
                                     dusk's when none is given) for apps that do not hand in a live palette
  generate.py live                   qml/Tacit/Kit/Live.qml: the tokens for any Tacit app, colours following the user's
                                     palette and see-through as the shell's do
  generate.py resolve colors.json    print every colour role, 8-bit and 16-bit (for the parity check)
"""
import json
import os
import pathlib
import sys
import textwrap

sys.path.insert(0, str(pathlib.Path(__file__).parent))
import colour as cl  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
TOKENS = json.loads((ROOT / "tokens/tokens.json").read_text())
BEGIN = "    // >>> tacit-kit tokens: generated by tacit-kit/tools/generate.py from tokens/tokens.json, do not edit by hand"
END = "    // <<< tacit-kit tokens"


def values(group):
    """The tokens of a group in file order, without the $ keys."""
    return [(k, v) for k, v in TOKENS[group].items() if not k.startswith("$")]


def m3(name):
    head, *rest = name.split("_")
    return "m3" + head + "".join(w.capitalize() for w in rest)


INK_REF = {"main": "colInkMain", "secondary": "colInkSecondary", "meta": "colInkMeta", "faint": "colInkFaint", "divider": "colInkDivider"}


def qml_expr(r):
    """A colour recipe as the QML expression the shell evaluates."""
    kind = r[0]
    if kind == "ink":
        return f"Appearance.colors.{INK_REF[r[1]]}"
    if kind == "palette":
        return f"Appearance.m3colors.{m3(r[1])}"
    if kind == "role":
        return f"root.{r[1]}"
    if kind == "mix":
        return f"ColorUtils.mix({qml_expr(r[1])}, {qml_expr(r[2])}, {r[3]})"
    if kind == "quieter":
        return f"root.quieter({qml_expr(r[1])}, {qml_expr(r[2])}, {r[3]})"
    if kind == "inkFor":
        return f"root.inkOn({r[1]}, {qml_expr(r[2])}, {qml_expr(r[3])})"
    raise ValueError(f"unknown recipe {r}")


# Appearance.inkFor along another colour than the palette's on-background (the "inkFor" recipe: risk, the overlay inks)
INK_ON = [
    "    // the first point on ground -> base -> white (or black) that reaches Lc: Appearance.inkFor along the colour `base`",
    "    function inkOn(lc, ground, base) {",
    '        const far = ground.hslLightness < 0.5 ? "#ffffff" : "#000000";',
    "        const at = t => t <= 1 ? ColorUtils.mix(base, ground, t) : ColorUtils.mix(far, base, t - 1);",
    "        let lo = 0, hi = 2;",
    "        for (let i = 0; i < 18; i++) {",
    "            const mid = (lo + hi) / 2;",
    "            if (Math.abs(ColorUtils.apcaLc(at(mid), ground)) < lc)",
    "                lo = mid;",
    "            else",
    "                hi = mid;",
    "        }",
    "        return at(hi);",
    "    }",
]


def qml_block():
    out = [BEGIN, ""]
    out.append("    // ---- colour roles (reference: the wallpaper's palette, the five APCA inks; text by brightness, never opacity)")
    for k, v in values("color"):
        if "$description" in v:
            out += textwrap.wrap(v["$description"], 120, initial_indent="    // ", subsequent_indent="    // ")
        out.append(f"    readonly property color {k}: {qml_expr(v['$value'])}")
    out += INK_ON
    out.append("")

    def group(name, typ, comment):
        out.append(f"    // ---- {comment}")
        out.append(f"    readonly property QtObject {name}: QtObject {{")
        for k, v in values(name):
            if "$deprecated" in v:
                out.append(f"        // deprecated: {v['$deprecated']}")
            val = json.dumps(v["$value"]) if typ == "string" else v["$value"]
            out.append(f"        readonly property {typ} {k}: {val}")
        out.append("    }")

    group("wash", "real", "washes: inkMain over the ground at these amounts")
    group("font", "string", "families")
    group("weight", "int", "weights on the wght axis")
    group("size", "int", "type sizes; hierarchy by size and weight")
    group("space", "int", "the 4 px grid's steps")
    group("height", "int", "heights")
    group("width", "int", "widths")
    group("radius", "int", "corners")
    group("icon", "int", "symbol sizes")
    out.append("    // ---- motion: easing.bezierCurve and duration for each named scheme (curve [] = linear)")
    out.append("    readonly property QtObject motion: QtObject {")
    for k, v in values("motion"):
        c = v["$value"]["curve"]
        curve = "[]" if c == "linear" else "[" + ", ".join(str(x) for x in c) + ", 1, 1]"
        out.append(f"        readonly property QtObject {k}: QtObject {{ readonly property var curve: {curve}; readonly property int ms: {v['$value']['ms']} }}")
    out.append("    }")
    group("state", "real", "states")
    out.append(END)
    return "\n".join(out)


def write_qml(path):
    p = pathlib.Path(path)
    s = p.read_text()
    a, b = s.find(BEGIN), s.find(END)
    if a < 0 or b < 0:
        sys.exit(f"generate: no tacit-kit markers in {p}")
    p.write_text(s[:a] + qml_block() + s[b + len(END):])
    print(f"wrote the token block of {p}")


def palette(colors_json):
    return json.loads(pathlib.Path(colors_json).read_text())


def resolve(pal):
    """Every colour role for one palette, as the shell resolves it."""
    pc = lambda name: cl.C.hex(pal[name])
    ground = pc("surface_container_low")
    ink = {k: cl.ink_for(v["$value"], ground, pc("on_background")) for k, v in values_ref_ink()}
    roles = {}

    def role(name):
        if name not in roles:
            roles[name] = ev(TOKENS["color"][name]["$value"])
        return roles[name]

    def ev(r):
        kind = r[0]
        if kind == "ink":
            return ink[r[1]]
        if kind == "palette":
            return pc(r[1])
        if kind == "role":
            return role(r[1])
        if kind == "mix":
            return cl.mix(ev(r[1]), ev(r[2]), r[3])
        if kind == "quieter":
            return cl.quieter(ev(r[1]), ev(r[2]), r[3])
        if kind == "inkFor":
            return cl.ink_for(r[1], ev(r[2]), ev(r[3]))
        raise ValueError(r)

    for k, v in values("color"):
        role(k)
    return {k: roles[k] for k, _ in values("color")}


def values_ref_ink():
    return [(k, v) for k, v in TOKENS["reference"]["ink"].items() if not k.startswith("$")]


def css(pal=None):
    lines = ["/* generated by tacit-kit/tools/generate.py from tokens/tokens.json; do not edit */", ":root {"]
    for g, unit in (("size", "px"), ("space", "px"), ("height", "px"), ("width", "px"), ("radius", "px"), ("icon", "px")):
        for k, v in values(g):
            lines.append(f"  --tacit-{g}-{k}: {v['$value']}{unit};")
    for k, v in values("wash"):
        lines.append(f"  --tacit-wash-{k}: {v['$value']};")
    for k, v in values("motion"):
        c, ms = v["$value"]["curve"], v["$value"]["ms"]
        ease = "linear" if c == "linear" else "cubic-bezier(" + ", ".join(str(x) for x in c) + ")"
        lines.append(f"  --tacit-motion-{k}: {ms}ms {ease};")
    if pal is not None:
        for k, c in resolve(pal).items():
            lines.append(f"  --tacit-color-{k}: {c.to_hex()};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def plain(r):
    """A colour recipe in words, for the docs' tables."""
    kind = r[0]
    if kind == "ink":
        return f"the {r[1]} ink"
    if kind == "palette":
        return f"the palette's `{r[1]}`"
    if kind == "role":
        return f"`{r[1]}`"
    if kind == "mix":
        return f"{plain(r[1])} at {round(r[3] * 100)} % over {plain(r[2])}"
    if kind == "quieter":
        return f"{plain(r[1])} faded towards {plain(r[2])} until Lc {r[3]}"
    if kind == "inkFor":
        return f"{plain(r[3])}, moved until Lc {r[1]} on {plain(r[2])}"
    raise ValueError(f"unknown recipe {r}")


def tables():
    out = ["<!-- generated by tacit-kit/tools/generate.py from tokens/tokens.json; do not edit -->", ""]
    for g in ("color", "wash", "size", "font", "weight", "space", "height", "width", "radius", "icon", "motion", "state"):
        out += [f"### {g}", "", "| Name | Value | Use |", "|---|---|---|"]
        for k, v in values(g):
            val = v["$value"]
            if g == "color":
                val = plain(val)
            elif g == "motion":
                val = f"{val['ms']} ms, " + ("linear" if val["curve"] == "linear" else "(" + ", ".join(str(x) for x in val["curve"]) + ")")
            use = v.get("$description", "") + (f" Deprecated: {v['$deprecated']}" if "$deprecated" in v else "")
            out.append(f"| `{k}` | {val} | {use} |")
        out.append("")
    return "\n".join(out)


def kit_defaults(pal):
    """The kit module's fallback tokens: the same names as the shell's Tacit, colours fixed for one palette."""
    out = ["// SPDX-License-Identifier: LGPL-3.0-or-later", "// generated by tacit-kit/tools/generate.py kit from tokens/tokens.json: do not edit",
           "// The tokens a Tacit.Kit part reads when the app hands in none (Kit.tokens). A Tacit app hands in the shell's",
           "// Tacit, which follows the wallpaper; these are one palette's colours, fixed.",
           "import QtQuick", "", "QtObject {"]
    for k, c in resolve(pal).items():
        out.append(f'    readonly property color {k}: "{c.to_hex()}"')
    out.append("    readonly property real windowSeeThrough: 0.15")
    out += kit_groups()
    out.append("}")
    return "\n".join(out) + "\n"


def kit_groups():
    """The non-colour token groups, as QML lines, the same in Defaults and Live."""
    out = []

    def group(name, typ):
        out.append(f"    readonly property QtObject {name}: QtObject {{")
        for k, v in values(name):
            val = json.dumps(v["$value"]) if typ == "string" else v["$value"]
            out.append(f"        readonly property {typ} {k}: {val}")
        out.append("    }")
    for g, typ in (("wash", "real"), ("font", "string"), ("weight", "int"), ("size", "int"), ("space", "int"), ("height", "int"), ("width", "int"),
                   ("radius", "int"), ("icon", "int"), ("state", "real")):
        group(g, typ)
    out.append("    readonly property QtObject motion: QtObject {")
    for k, v in values("motion"):
        c = v["$value"]["curve"]
        curve = "[]" if c == "linear" else "[" + ", ".join(str(x) for x in c) + ", 1, 1]"
        out.append(f"        readonly property QtObject {k}: QtObject {{ readonly property var curve: {curve}; readonly property int ms: {v['$value']['ms']} }}")
    out.append("    }")
    return out


def live_expr(r):
    """A colour recipe as an expression over Live.qml's palette and helpers."""
    kind = r[0]
    if kind == "ink":
        return f"live.inks.{r[1]}"
    if kind == "palette":
        return f'live.pc("{r[1]}")'
    if kind == "role":
        return f"live.{r[1]}"
    if kind == "mix":
        return f"live.mix({live_expr(r[1])}, {live_expr(r[2])}, {r[3]})"
    if kind == "quieter":
        return f"live.quieter({live_expr(r[1])}, {live_expr(r[2])}, {r[3]})"
    if kind == "inkFor":
        return f"live.inkFor({r[1]}, {live_expr(r[2])}, {live_expr(r[3])})"
    raise ValueError(r)


def kit_live():
    """Live.qml: the kit's tokens for any Tacit app, following the user's palette (the generated colors.json the shell
    writes for each wallpaper) and see-through, with the shell's colour maths. Non-colour tokens as in Defaults."""
    out = ["// SPDX-License-Identifier: LGPL-3.0-or-later", "// generated by tacit-kit/tools/generate.py live from tokens/tokens.json: do not edit",
           "// The tokens a Tacit.Kit part reads in any Tacit app: the colours follow the wallpaper as the shell's do (the",
           "// palette the shell generates, read and watched here), with the same maths (Appearance.inkFor, Tacit.quieter,",
           "// ColorUtils.mix). `ready` turns true once the palette is read; until then, and where there is none, Kit uses",
           "// Defaults.",
           "import QtQuick", "import Quickshell", "import Quickshell.Io", "",
           "// a Scope with the FileViews as its children: Quickshell starts only the files it finds in the child list",
           "Scope {", "    id: live",
           '    readonly property string home: Quickshell.env("HOME")',
           '    readonly property string generated: (Quickshell.env("XDG_STATE_HOME") || live.home + "/.local/state") + "/quickshell/user/generated"',
           '    readonly property string configPath: (Quickshell.env("XDG_CONFIG_HOME") || live.home + "/.config") + "/illogical-impulse/config.json"',
           "    property var pal: ({})",
           "    property real seeThroughScale: 1",
           "    property var transparency: ({ enable: true, automatic: true, backgroundTransparency: 0.15 })",
           "    readonly property bool ready: live.pal.surface_container_low !== undefined",
           "",
           "    FileView {",
           "        id: paletteFile",
           '        path: live.generated + "/colors.json"',
           "        watchChanges: true; printErrors: false",
           "        onFileChanged: reload()",
           "        onLoaded: { try { live.pal = JSON.parse(text()); } catch (e) {} }",
           "    }",
           "    FileView {",
           "        id: seeThroughFile",
           '        path: live.generated + "/seethrough.json"',
           "        watchChanges: true; printErrors: false",
           "        onFileChanged: reload()",
           "        onLoaded: { try { live.seeThroughScale = Number(JSON.parse(text()).scale ?? 1); } catch (e) {} }",
           "    }",
           "    FileView {",
           "        id: configFile",
           "        path: live.configPath",
           "        watchChanges: true; printErrors: false",
           "        onFileChanged: reload()",
           "        onLoaded: { try { const t = JSON.parse(text()).appearance?.transparency; if (t) live.transparency = t; } catch (e) {} }",
           "    }",
           "",
           "    // the shell's colour maths (tools/colour.py is the same, checked against it)",
           '    function pc(name) { return Qt.color(live.pal[name] ?? "#000000"); }',
           "    function q(c) { return Qt.color(String(c)); }",
           "    function mix(c1, c2, p) {",
           "        const a = live.q(c1), b = live.q(c2);",
           "        return Qt.rgba(p * a.r + (1 - p) * b.r, p * a.g + (1 - p) * b.g, p * a.b + (1 - p) * b.b, p * a.a + (1 - p) * b.a);",
           "    }",
           "    function lightness(c) { return (Math.max(c.r, c.g, c.b) + Math.min(c.r, c.g, c.b)) / 2; }",
           "    function apca(text, ground) {",
           "        const y = c => { const v = 0.2126729 * Math.pow(c.r, 2.4) + 0.7151522 * Math.pow(c.g, 2.4) + 0.0721750 * Math.pow(c.b, 2.4);",
           "                         return v > 0.022 ? v : v + Math.pow(0.022 - v, 1.414); };",
           "        const yt = y(live.q(text)), yb = y(live.q(ground));",
           "        if (yb > yt) { const s = (Math.pow(yb, 0.56) - Math.pow(yt, 0.57)) * 1.14; return s < 0.1 ? 0 : (s - 0.027) * 100; }",
           "        const s = (Math.pow(yb, 0.65) - Math.pow(yt, 0.62)) * 1.14; return s > -0.1 ? 0 : (s + 0.027) * 100;",
           "    }",
           "    function inkFor(lc, ground, onBackground) {",
           "        const far = live.lightness(ground) < 0.5 ? Qt.rgba(1, 1, 1, 1) : Qt.rgba(0, 0, 0, 1);",
           "        const at = t => t <= 1 ? live.mix(onBackground, ground, t) : live.mix(far, onBackground, t - 1);",
           "        let lo = 0, hi = 2;",
           "        for (let i = 0; i < 18; i++) { const mid = (lo + hi) / 2; if (Math.abs(live.apca(at(mid), ground)) < lc) lo = mid; else hi = mid; }",
           "        return at(hi);",
           "    }",
           "    function quieter(fg, bg, lc) {",
           "        let lo = 0, hi = 1;",
           "        for (let i = 0; i < 16; i++) { const mid = (lo + hi) / 2; if (Math.abs(live.apca(live.mix(fg, bg, mid), bg)) >= lc) hi = mid; else lo = mid; }",
           "        return live.mix(fg, bg, hi);",
           "    }",
           "",
           "    readonly property var inks: {",
           '        const g = live.pc("surface_container_low"), on = live.pc("on_background");',
           "        return { " + ", ".join(f'{k}: live.inkFor({v["$value"]}, g, on)' for k, v in values_ref_ink()) + " };",
           "    }"]
    for k, v in values("color"):
        out.append(f"    readonly property color {k}: {live_expr(v['$value'])}")
    out.append("    readonly property real windowSeeThrough: (live.transparency.enable === false ? 0")
    out.append("        : live.transparency.automatic !== false ? 0.15 : Number(live.transparency.backgroundTransparency ?? 0.15)) * live.seeThroughScale")
    out += kit_groups()
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if cmd == "qml" and len(sys.argv) == 3:
        write_qml(sys.argv[2])
    elif cmd == "css":
        pal = palette(sys.argv[2]) if len(sys.argv) == 3 else None
        (ROOT / "generated/tokens.css").write_text(css(pal))
        print("wrote generated/tokens.css")
    elif cmd == "tables":
        (ROOT / "generated/tables.md").write_text(tables())
        print("wrote generated/tables.md")
    elif cmd == "live":
        (ROOT / "qml/Tacit/Kit/Live.qml").write_text(kit_live())
        print("wrote qml/Tacit/Kit/Live.qml")
    elif cmd == "kit":
        src = sys.argv[2] if len(sys.argv) == 3 else str(pathlib.Path(os.environ.get("TACIT_MOCKS", pathlib.Path.home() / ".cache/tacit-mocks")) / "state-dusk/quickshell/user/generated/colors.json")
        out = ROOT / "qml/Tacit/Kit/Defaults.qml"
        out.write_text(kit_defaults(palette(src)))
        print(f"wrote {out}")
    elif cmd == "resolve" and len(sys.argv) == 3:
        for k, c in resolve(palette(sys.argv[2])).items():
            print(k, c.to_hex(), *c.u16())
    else:
        sys.exit(__doc__)
